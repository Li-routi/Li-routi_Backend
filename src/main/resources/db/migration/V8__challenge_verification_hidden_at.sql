-- 신고가 임계값만큼 쌓인 인증을 전체 회원에게 가린다.
--
-- NULL 이 "노출 중"이다. 기본값을 두지 않는 이유는 그 상태가 대다수이고, NULL 이면
-- 인덱스에도 담기지 않아 조회가 이득을 본다.
--
-- 소프트 삭제가 아니다. 행도 스트릭도 그대로 두고 노출만 막는다.
ALTER TABLE `challenge_verification`
    ADD COLUMN `hidden_at` datetime(6) DEFAULT NULL;

-- 인증을 읽는 세 경로(피드 · 내 인증 · 게시글 수)가 전부 `hidden_at IS NULL` 을 달고 돈다.
--
-- 인덱스를 따로 두지 않는다. 가려진 행은 극소수라 이 조건의 선택도가 거의 없고,
-- 세 쿼리 모두 challenge_id · member_challenge_id 로 먼저 좁힌 뒤 이 조건을 적용한다.
-- 인덱스를 넣으면 옵티마이저가 그쪽을 먼저 타서 오히려 느려질 수 있다(#45 에서 실측으로
-- 확인한 현상이다 — 선택도 낮은 인덱스를 추가했더니 조인 순서가 뒤집혀 7배 느려졌다).
