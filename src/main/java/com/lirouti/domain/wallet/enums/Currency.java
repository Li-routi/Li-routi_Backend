package com.lirouti.domain.wallet.enums;

/**
 * 재화 종류.
 *
 * <p><b>화면 문구는 여기 두지 않는다.</b> 시안 안에서도 표기가 갈린다 — 탭은 "파란보석"인데
 * 충전 팝업은 "550코인"이다. 서버가 문구를 내려주면 문안을 고칠 때마다 배포가 필요해진다.
 * 클라이언트가 이 값에 맞는 이름을 가진다(스트릭 문구·신고 사유 문구와 같은 기준).
 *
 * <p>지갑은 여전히 <b>재화 종류를 구분하지 않고 동작한다.</b> 어느 쪽으로 결정되든 스키마와
 * 지갑 코드가 바뀌지 않도록 한 것이고, 그 성질은 아래 결정 뒤에도 유지한다.
 */
public enum Currency {

    /**
     * 시안의 파란 보석. <b>무료 재화</b>다 — 챌린지 인증으로 번다.
     *
     * <p>이 주석은 원래 "현금 결제로 얻는다"고 적혀 있었다. 기획 확인 결과 반대였다.
     */
    GEM,

    /**
     * 시안의 주황 보석("토파즈"). <b>유료 재화</b>다 — 현금으로 산다.
     *
     * <p>이 주석은 원래 "{@link #GEM} 으로 교환해 얻는다"고 적혀 있었다. 반대였다.
     */
    TOPAZ
}
