package com.lirouti.domain.wallet.enums;

/**
 * 재화 종류.
 *
 * <p><b>화면 문구는 여기 두지 않는다.</b> 시안 안에서도 표기가 갈린다 — 탭은 "파란보석"인데
 * 충전 팝업은 "550코인"이다. 서버가 문구를 내려주면 문안을 고칠 때마다 배포가 필요해진다.
 * 클라이언트가 이 값에 맞는 이름을 가진다(스트릭 문구·신고 사유 문구와 같은 기준).
 *
 * <p><b>둘은 서로를 대신하지 못한다.</b> 재화마다 살 수 있는 아이템이 정해져 있어, 한쪽이
 * 모자란다고 다른 쪽으로 결제되지 않는다. 교환은 {@link #TOPAZ} → {@link #GEM} 한 방향뿐이다.
 *
 * <p>지갑은 <b>재화별로 잔액을 따로 들되, 그 재화가 무엇을 살 수 있는지는 해석하지 않는다.</b>
 * 어느 아이템을 어느 재화로 파는지는 상점의 몫이고, 지갑은 "이 재화를 이만큼 더하고 뺀다"만
 * 안다. 그래서 재화가 하나 늘어도 지갑 코드는 바뀌지 않는다.
 */
public enum Currency {

    /**
     * 시안의 파란 보석. <b>무료 재화</b>다 — 챌린지 인증으로 벌거나 {@link #TOPAZ} 로 산다.
     *
     * <p><b>어떻게 얻든 무상이다.</b> {@code paid_balance} 를 쓰지 않는다 — {@code TOPAZ} 를
     * 이것으로 바꾼 시점에 결제한 재화를 쓴 것이라, 남은 {@code GEM} 은 환불 대상이 아니다.
     *
     * <p><b>여기에 유상 잔액을 만들지 말 것.</b> 리워드 회수가 이 재화에서 일어나므로,
     * 유상 잔액이 생기면 회수가 환불 대상 재화를 깎기 시작한다.
     *
     * <p>이 주석은 원래 "현금 결제로 얻는다"고 적혀 있었다. 기획 확인 결과 반대였다.
     */
    GEM,

    /**
     * 시안의 주황 보석("토파즈"). <b>유료 재화</b>다 — 현금으로 산다.
     *
     * <p>유상·무상이 실제로 갈리는 것은 이쪽뿐이다 — 현금으로 산 몫과 충전 보너스다.
     *
     * <p>이 주석은 원래 "{@link #GEM} 으로 교환해 얻는다"고 적혀 있었다. 반대였다.
     */
    TOPAZ
}
