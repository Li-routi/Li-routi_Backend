package com.lirouti.domain.wallet.enums;

import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * 재화 종류.
 *
 * <p><b>화면 문구는 여기 두지 않는다.</b> 시안 안에서도 표기가 갈린다 — 탭은 "파란보석"인데
 * 충전 팝업은 "550코인"이다. 서버가 문구를 내려주면 문안을 고칠 때마다 배포가 필요해진다.
 * 클라이언트가 이 값에 맞는 이름을 가진다(스트릭 문구·신고 사유 문구와 같은 기준).
 *
 * <p><b>둘은 서로를 대신하지 못한다.</b> 아이템마다 결제 재화가 정해져 있어, 한쪽이 모자란다고
 * 다른 쪽으로 결제되지 않는다.
 *
 * <p>지갑은 <b>재화별로 잔액을 따로 들되, 그 재화가 무엇을 살 수 있는지는 해석하지 않는다.</b>
 * 어느 아이템을 어느 재화로 파는지는 상점의 몫이고, 지갑은 "이 재화를 이만큼 더하고 뺀다"만
 * 안다. 그래서 재화가 하나 늘어도 지갑 코드는 바뀌지 않는다.
 */
@Getter
@AllArgsConstructor
public enum Currency {

    /**
     * 시안의 파란 보석. <b>유료 재화</b>다 — 현금으로만 얻는다.
     *
     * <p><b>챌린지로는 벌 수 없다.</b> 여기에 리워드를 주면 인증만 하면 유료 재화가 공짜로
     * 생긴다. 리워드는 {@link #TOPAZ} 다.
     *
     * <p>유상·무상이 실제로 갈리는 것은 이쪽이다 — 현금으로 산 몫(유상)과 충전 보너스(무상).
     */
    GEM(true),

    /**
     * 시안의 주황 보석("토파즈"). <b>무료 재화</b>다 — 챌린지 인증 리워드로 번다.
     *
     * <p>현금으로 사지 않으므로 <b>어떻게 얻든 무상이다.</b> {@code paid_balance} 를 쓰지 않는다.
     */
    TOPAZ(false);

    /**
     * 이 재화에 <b>유상 잔액이 생길 수 있는가.</b>
     *
     * <p>무료 재화는 현금으로 사지 않으므로 유상 잔액이 있을 수 없다. 규칙을 여기 두는 이유는
     * <b>"무료냐 유료냐" 가 재화의 성질이기 때문</b>이다 — 지갑이나 DB 제약에 재화 이름을
     * 박아 두면, 성질이 바뀔 때 고쳐야 할 자리가 흩어진다. 이 값은 실제로 세 번 뒤집혔다.
     *
     * <p><b>왜 막아야 하나.</b> 리워드 회수는 무료 재화에서 일어난다. 그 재화에 유상 잔액이
     * 생기면 <b>회수가 환불 대상 재화를 깎기 시작한다</b> — 무상분을 다 쓴 사용자가 글을
     * 지우면 현금으로 산 몫에서 빠진다. 지금은 그런 값을 만드는 코드가 없어서 안전할 뿐이라,
     * 교환(충전 이슈)을 만들며 "결제한 것이니 유상으로 기록하자" 는 판단이 나오면 그 순간
     * 열린다. <b>그 판단이 코드로 들어오는 시점에 막는다.</b>
     */
    private final boolean paidBalanceAllowed;
}
