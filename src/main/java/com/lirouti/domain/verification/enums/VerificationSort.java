package com.lirouti.domain.verification.enums;

/**
 * 인증 목록 정렬.
 *
 * <p><b>기본은 {@link #LATEST} 다.</b> 파라미터를 안 보내던 클라이언트의 화면이 조용히 달라지면
 * 안 되므로, 기본값은 반드시 이 기능이 생기기 전의 동작이어야 한다.
 *
 * <h3>둘의 페이징 방식이 다르다</h3>
 * {@code LATEST} 는 커서로 끝까지 넘길 수 있고, {@code LIKES} 는 <b>상위 몇 개만</b> 준다.
 * 응답 형태는 같다 — {@code LIKES} 도 {@code nextCursor} 가 {@code null} 이고
 * {@code hasNext} 가 {@code false} 로 나가므로, 클라이언트는 하던 대로 커서 규약을 따르면
 * 자연히 한 페이지에서 멈춘다. <b>나중에 페이징을 붙여도 계약이 깨지지 않는다.</b>
 *
 * <p>{@code LIKES} 를 페이징하지 않는 이유는 <b>정렬 키가 스크롤 도중 바뀌기 때문</b>이다.
 * 좋아요가 하나 눌리면 그 인증이 위로 올라가, 다음 페이지에서 이미 본 항목이 다시 나오거나
 * 밀려 내려간 항목을 건너뛴다. 이 저장소는 같은 문제를 이미 한 번 겪었다 — 피드 커서를
 * {@code verified_at} 이 아니라 {@code id} 로 잡은 이유가 그것이고, 좋아요 수는
 * {@code verified_at} 보다 훨씬 자주 바뀐다.
 *
 * <p>완전한 방법이 없다는 점도 근거다. 정렬 키가 변하면 어떤 페이지네이션이든 근사일 뿐이라,
 * "정확한 것처럼" 계약을 내주는 대신 <b>범위를 좁혀 정직하게</b> 두었다.
 */
public enum VerificationSort {

    /**
     * 최신순. 인증 행이 만들어진 순서({@code id} 내림차순)다.
     *
     * <p><b>"사진을 마지막으로 올린 순서"가 아니다.</b> 지우고 다시 인증하면 같은 행을
     * 되살리므로 목록에서는 원래 자리에 그대로 있다. 사용자가 이 정렬에서 기대하는 것은
     * "누가 최근에 인증했나"이지 "누가 최근에 사진을 갈아끼웠나"가 아니라고 보았다.
     *
     * <p>{@code verified_at} 으로 바꾸면 <b>사진만 다시 올려 피드 위로 가는 길</b>이 열린다.
     */
    LATEST,

    /** 좋아요순. 같은 수면 최신순으로 가른다 — 순서가 흔들리지 않게 {@code id} 로 못 박는다. */
    LIKES
}
