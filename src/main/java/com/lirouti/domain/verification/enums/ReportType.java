package com.lirouti.domain.verification.enums;

/**
 * 인증 게시글 신고 사유.
 *
 * <p><b>화면 문구는 여기 두지 않는다.</b> 서버가 문구를 내려주면 문구를 고칠 때마다 서버 배포가
 * 필요해진다. 클라이언트가 이 값에 맞는 문장을 가진다 — 에러 메시지를 코드로만 만드는 것과
 * 같은 기준이다(exception_convention).
 *
 * <h3>숨김 판정에는 쓰이지 않는다</h3>
 * 신고 누적 자동 숨김은 <b>건수만</b> 센다. 사유별 가중치를 두면 "몇 건이면 가려지나"가 사유
 * 조합에 따라 달라져 설명하기 어렵고, 오탐일 때 되짚기도 어렵다. <b>우선 기록만 하고</b>
 * 데이터가 쌓인 뒤 판단한다.
 *
 * <h3>둘은 나중에 서버가 스스로 판정할 여지가 있다</h3>
 * {@link #REUSED} 는 승격 때 이미 다루는 ETag 로 같은 바이트의 재사용을 기계적으로 걸러낼 수
 * 있고, {@link #IRRELEVANT} 는 AI 심사가 이미 보는 기준이다. <b>심사를 통과한 사진에
 * {@code IRRELEVANT} 신고가 쌓이면 심사가 느슨하다는 신호</b>로 읽을 수 있다. 그 판단의
 * 근거를 만들려고 사유를 남긴다.
 */
public enum ReportType {

    /** 실제 루틴 수행과 무관한 사진. AI 심사({@code CHALLENGE422_1})가 보는 기준과 겹친다. */
    IRRELEVANT,

    /** 예전에 인증했던 사진의 재사용. */
    REUSED,

    /** 타인의 사진 도용. */
    STOLEN,

    /** 스팸 또는 광고성 콘텐츠. */
    SPAM,

    /**
     * 그 밖의 사유. <b>이 값일 때만 직접 입력({@code reason})이 필수다.</b>
     *
     * <p>나머지 넷은 화면에 입력란이 없어 {@code reason} 을 받지 않는다.
     */
    ETC
}
