package com.lirouti.domain.verification.enums;

/**
 * 인증 한 건의 심사 상태.
 *
 * <p><b>{@code REJECTED} 는 없다.</b> 반려는 행을 만들지 않고 422 로 끝나기 때문이다.
 * 반려 행을 남기면 유니크 키 {@code (참여, 회차, 날짜)} 가 그날의 재시도를 막아, 다시 찍어
 * 올리려는 사용자를 막게 된다. 보류가 반려로 확정되면 <b>행을 지우고 사진도 지운다</b> —
 * 오늘 반려와 같은 결과로 만든다.
 */
public enum ReviewStatus {

    /**
     * 심사가 답을 못 줘 보류 중이다. <b>사진이 아직 대기 prefix 에 있어 공개 주소가 없다.</b>
     *
     * <p>어느 조회에 들어가는지는 database-schema.md 가 표로 정해 뒀다. 기본은 제외이고,
     * 내 인증 목록(본인 것만)과 완료 여부·완료자 수만 포함한다.
     */
    PENDING,

    /**
     * 공개된 정상 인증. 심사를 통과했거나, 심사가 답을 못 줘 상한까지 간 뒤 통과시킨 것이다.
     *
     * <p>심사가 꺼져 있던 시절의 인증도 여기 들어간다 — 마이그레이션이 기존 행을 이 값으로 채운다.
     */
    APPROVED
}
