/**
 * 아바타에서 아이템이 차지하는 자리.
 *
 * <p><b>넷은 서로 겹치지 않는다.</b> 한 아이템이 한 슬롯만 차지하므로 "무엇을 입으면 무엇이
 * 벗겨지는가" 를 정의할 필요가 없다 — 같은 슬롯의 이전 아이템이 교체될 뿐이다.
 *
 * <p><b>화면의 "전체" 탭은 여기 없다.</b> 그것은 분류가 아니라 필터 없음이라, 목록 요청에서
 * 슬롯을 생략한 것으로 표현한다. 값으로 두면 아이템이 "모든 자리를 차지한다" 는 뜻을 가질 수
 * 있게 되고, 여러 슬롯을 덮는 아이템을 두지 않기로 한 결정과 어긋난다.
 *
 * <p>화면 문구는 클라이언트가 붙인다 — 재화 이름·스트릭 문구와 같은 기준이다.
 */
public enum AvatarSlot {

    /** 머리 */
    HEAD,

    /** 얼굴 */
    FACE,

    /** 몸 */
    BODY,

    /** 손 */
    HAND
}
