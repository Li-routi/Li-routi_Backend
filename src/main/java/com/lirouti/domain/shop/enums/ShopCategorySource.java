package com.lirouti.domain.shop.enums;

/**
 * 탭을 눌렀을 때 무엇을 가져와야 하는가.
 *
 * <p><b>탭 목록이 슬롯 목록이 아니기 때문에 필요하다.</b> 아이템 탭 셋은 아바타 아이템을
 * 가져오지만 캐릭터 탭은 다른 것을 가져온다 — 캐릭터는 {@code avatar_item} 이 아니라 돈이
 * 아니라 조건으로 열리는 별개의 것이다.
 *
 * <p>이 값이 없으면 클라이언트가 "전체" 와 "캐릭터" 를 구분할 수 없다. 둘 다 슬롯이
 * 비어 있어서다.
 */
public enum ShopCategorySource {

    /** 아바타 아이템 목록에서 가져온다. 슬롯이 있으면 그 슬롯으로 거르고, 없으면 전부. */
    ITEM,

    /** 보유·미보유 캐릭터 목록에서 가져온다. 아이템 목록과 원천이 다르다. */
    CHARACTER
}
